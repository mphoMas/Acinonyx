"""
mas.organization.profile_pod: Autonomous Multi-Agent Squad for Company Profile & JV Strategy.
Coordinates a specialized strike pod from the 7 Capability Guilds to evaluate,
stress-test, and enhance AcinonyxLabs' corporate profile, technical moats, and joint venture contracts.

Architect: Acinonyx
"""

from __future__ import annotations

import hashlib
import logging
import time
from dataclasses import dataclass, field
from typing import Dict, Optional

from mas.core.event_bus import EventBus
from mas.core.message import Message, MessageMetadata, Role
from mas.organization.roles import (
    AdversarialRedTeamAgent,
    DataEngineerAgent,
    MarketResearcherAgent,
    ProductManagerAgent,
    TechnicalWriterAgent,
)
from mas.providers.base import LLMProvider
from mas.providers.factory import create_llm_provider
from mas.squad.squad import ArchitectAgent

logger = logging.getLogger("mas.profile_pod")


@dataclass
class ProfileEvaluationResult:
    pod_id: str
    success: bool
    market_intelligence: str = ""
    product_strategy: str = ""
    technical_architecture_review: str = ""
    data_engineering_review: str = ""
    adversarial_red_team_audit: str = ""
    executive_synthesis: str = ""
    merkle_provenance_hash: str = ""
    elapsed_seconds: float = 0.0
    tokens_consumed: int = 0
    artifacts: Dict[str, str] = field(default_factory=dict)

    def to_markdown_report(self) -> str:
        """Render the complete multi-agent evaluation into an executive markdown dossier."""
        return f"""# AcinonyxLabs Multi-Agent Profile & JV Review Dossier
**Generated by:** MAS-Core Liquid Strike Pod (`{self.pod_id}`)  
**Execution Timestamp:** {time.strftime('%Y-%m-%d %H:%M:%S UTC', time.gmtime())}  
**Merkle Provenance Hash:** `{self.merkle_provenance_hash}`  
**Processing Duration:** {self.elapsed_seconds:.2f}s  
**Total Tokens Consumed:** {self.tokens_consumed}  

---

## 📊 Executive Synthesis & Enhancement Blueprint
*Authored by: Technical Writer & Deal Packager (`technical_writer`)*

{self.executive_synthesis}

---

## 🎯 1. Market Sizing & Competitive Moats Assessment
*Authored by: Market Intelligence & Domain Lead (`market_researcher`)*

{self.market_intelligence}

---

## 💼 2. Commercial Packaging & Joint Venture Structure
*Authored by: Head of Product & Commercial Strategy (`product_lead`)*

{self.product_strategy}

---

## 🏛️ 3. Technical Architecture & Background IP Verification
*Authored by: Chief Principal Agentic Engineer & Architect (`chief_architect`)*

{self.technical_architecture_review}

---

## 🗄️ 4. Enterprise Cloud Data & Governance Architecture
*Authored by: Staff Data Systems Architect (`data_engineer`)*

{self.data_engineering_review}

---

## 🛡️ 5. Adversarial Red-Team & Due Diligence Stress-Test
*Authored by: Adversarial Chaos Engineer & Due Diligence Auditor (`adversarial_red_team`)*

{self.adversarial_red_team_audit}

---
*Verified and sealed under Project ACINONYX (MAS-Core) cryptographic provenance protocol.*
"""


class CompanyProfilePod:
    """
    An autonomous multi-agent council dynamically assembled to review,
    strengthen, and stress-test the AcinonyxLabs corporate dossier and JV agreements.
    """

    def __init__(
        self,
        llm_provider: Optional[LLMProvider] = None,
        event_bus: Optional[EventBus] = None,
        pod_id: Optional[str] = None,
    ) -> None:
        self.pod_id = pod_id or f"profile_pod_{hashlib.sha256(str(time.time()).encode()).hexdigest()[:8]}"
        self.llm_provider = llm_provider or create_llm_provider("auto")
        self.event_bus = event_bus or EventBus(log_history=True)
        self.topic = f"org:pod:{self.pod_id}"
        self.tokens_consumed = 0

        # Initialize the 6 specialized guild agents with shared LLM provider & event bus
        self.market_researcher = MarketResearcherAgent(
            llm_provider=self.llm_provider,
            event_bus=self.event_bus,
        )
        self.product_lead = ProductManagerAgent(
            llm_provider=self.llm_provider,
            event_bus=self.event_bus,
        )
        self.chief_architect = ArchitectAgent(
            name="chief_architect",
            system_prompt=(
                "You are the Chief Principal Agentic Engineer & Architect for AcinonyxLabs. "
                "You rigorously evaluate company technical materials for architectural purity, "
                "mathematical bounds, anti-sycophantic invariants, and Model Context Protocol (MCP) compliance."
            ),
            llm_provider=self.llm_provider,
            event_bus=self.event_bus,
        )
        self.data_engineer = DataEngineerAgent(
            llm_provider=self.llm_provider,
            event_bus=self.event_bus,
        )
        self.adversarial_red_team = AdversarialRedTeamAgent(
            llm_provider=self.llm_provider,
            event_bus=self.event_bus,
        )
        self.technical_writer = TechnicalWriterAgent(
            llm_provider=self.llm_provider,
            event_bus=self.event_bus,
        )

        self.agents = [
            self.market_researcher,
            self.product_lead,
            self.chief_architect,
            self.data_engineer,
            self.adversarial_red_team,
            self.technical_writer,
        ]

        # Attach all agents to pod event bus
        for agent in self.agents:
            if hasattr(agent, "attach_event_bus"):
                agent.attach_event_bus(self.event_bus, topic=self.topic)

    async def _broadcast(self, content: str, sender: str = "pod_supervisor") -> None:
        msg = Message(
            sender=sender,
            recipient="broadcast",
            role=Role.SYSTEM,
            content=content,
            metadata=MessageMetadata(topic=self.topic, extra={"pod_id": self.pod_id}),
        )
        await self.event_bus.publish(msg)

    def _compute_merkle_provenance(self, artifacts: Dict[str, str]) -> str:
        hasher = hashlib.sha256()
        for k in sorted(artifacts.keys()):
            hasher.update(k.encode("utf-8"))
            hasher.update(artifacts[k].encode("utf-8"))
        hasher.update(self.pod_id.encode("utf-8"))
        return hasher.hexdigest()

    async def execute_review(
        self,
        profile_content: str,
        jv_terms_content: str = "",
    ) -> ProfileEvaluationResult:
        """
        Execute end-to-end multi-agent evaluation across all 6 specialized domains.
        """
        start_time = time.time()
        artifacts: Dict[str, str] = {}
        await self._broadcast(f"Assembled CompanyProfilePod '{self.pod_id}' for corporate profile review.")

        context_summary = (
            f"=== ACINONYXLABS COMPANY PROFILE ===\n{profile_content}\n\n"
            f"=== ACINONYXLABS JV TERM SHEET FRAMEWORK ===\n{jv_terms_content}\n"
        )

        # ---------------------------------------------------------------------
        # Phase 1: Market Intelligence & Moat Analysis
        # ---------------------------------------------------------------------
        logger.info("[%s] Phase 1: Market Intelligence & Moat Analysis", self.pod_id)
        p1_prompt = (
            "Analyze the attached AcinonyxLabs Company Profile and JV Term Sheet from a Market Intelligence perspective:\n"
            "1. Market Sizing: What macro trends in Enterprise AI & Autonomous Multi-Agent Systems support this positioning?\n"
            "2. Competitive Moat: How does AcinonyxLabs differentiate against generic AI frameworks (LangChain, AutoGen, CrewAI, Palantir)?\n"
            "3. Key Market Opportunities: What high-value enterprise verticals (FinTech, Retail, Logistics) should the JV prioritize?\n"
            "4. Strategic Recommendations: How can the market narrative be sharpened for enterprise investors and commercial partners?\n\n"
            f"{context_summary}"
        )
        resp1 = await self.market_researcher.step(
            Message(sender="supervisor", recipient=self.market_researcher.name, role=Role.USER, content=p1_prompt)
        )
        artifacts["phase1_market_intelligence"] = resp1.content

        # ---------------------------------------------------------------------
        # Phase 2: Product Strategy & Commercial Structuring
        # ---------------------------------------------------------------------
        logger.info("[%s] Phase 2: Product Strategy & Commercial Packaging", self.pod_id)
        p2_prompt = (
            "Review the AcinonyxLabs service offerings and Joint Venture commercial model:\n"
            "1. Commercial Packaging: Are the 3 service pillars and engagement models clear, high-margin, and scalable?\n"
            "2. JV Term Sheet Viability: Critique the proposed Equity/Revenue split, Steering Committee governance, and Background vs. Foreground IP allocation.\n"
            "3. Customer ICP: Define the ideal strategic partner persona that maximizes commercial synergy.\n"
            "4. Recommendations: Provide specific enhancements to improve deal conversion and partnership clarity.\n\n"
            f"Prior Market Findings:\n{artifacts['phase1_market_intelligence']}\n\n"
            f"{context_summary}"
        )
        resp2 = await self.product_lead.step(
            Message(sender="supervisor", recipient=self.product_lead.name, role=Role.USER, content=p2_prompt)
        )
        artifacts["phase2_product_strategy"] = resp2.content

        # ---------------------------------------------------------------------
        # Phase 3: Architectural Validation & Invariants
        # ---------------------------------------------------------------------
        logger.info("[%s] Phase 3: Architecture & Technical Moats Validation", self.pod_id)
        p3_prompt = (
            "As Chief Systems Architect, rigorously assess the technical specifications and invariants:\n"
            "1. MAS-Core Runtime: Does the profile clearly convey the architectural advantage of a deterministic async micro-kernel over bloated mega-frameworks?\n"
            "2. Anti-Sycophancy (MAD): Is the blind-masked debate protocol and contrarian injection mechanism sufficiently defended?\n"
            "3. Memory & Telemetry: How effectively does the Comms Vault (SQLite WAL FTS5) establish defensible institutional memory?\n"
            "4. Background IP Protection: Are the technical boundaries between Background IP and partner-developed Foreground IP watertight?\n\n"
            f"{context_summary}"
        )
        resp3 = await self.chief_architect.step(
            Message(sender="supervisor", recipient=self.chief_architect.name, role=Role.USER, content=p3_prompt)
        )
        artifacts["phase3_technical_architecture"] = resp3.content

        # ---------------------------------------------------------------------
        # Phase 4: Data Systems & Lakehouse Architecture
        # ---------------------------------------------------------------------
        logger.info("[%s] Phase 4: Cloud Data Engineering & Governance", self.pod_id)
        p4_prompt = (
            "Assess the Google Cloud Platform, BigQuery, and enterprise data stack capabilities in the profile:\n"
            "1. Enterprise Data Credibility: Does the profile convincingly showcase deep enterprise data engineering expertise (dbt, Composer, Dataform, BigQuery)?\n"
            "2. Data Governance & Contracts: How well are DAMA/DMBoK and schema-first data contracts integrated with the agent runtime?\n"
            "3. Specific Additions: What specific enterprise data metrics, benchmarks, or patterns should be highlighted to reassure enterprise buyers?\n\n"
            f"{context_summary}"
        )
        resp4 = await self.data_engineer.step(
            Message(sender="supervisor", recipient=self.data_engineer.name, role=Role.USER, content=p4_prompt)
        )
        artifacts["phase4_data_engineering"] = resp4.content

        # ---------------------------------------------------------------------
        # Phase 5: Adversarial Red-Team Stress-Test
        # ---------------------------------------------------------------------
        logger.info("[%s] Phase 5: Adversarial Due Diligence Stress-Test", self.pod_id)
        p5_prompt = (
            "Perform an uncompromising Adversarial Due Diligence Audit on AcinonyxLabs as a hostile venture investor or partner counsel:\n"
            "1. Skeptical Probes: What claims in the profile sound like buzzwords or unproven assertions that a technical auditor would challenge?\n"
            "2. Legal & Commercial Attack Vectors: Where could a partner exploit loopholes in the JV Term Sheet (IP leakage, non-circumvention, scope creep)?\n"
            "3. Operational Risks: What are the primary bottlenecks in scaling Liquid Strike Pods and multi-agent systems in client environments?\n"
            "4. Hard Remediation: What concrete defenses, evidence, or contractual revisions must be added immediately?\n\n"
            f"{context_summary}"
        )
        resp5 = await self.adversarial_red_team.step(
            Message(sender="supervisor", recipient=self.adversarial_red_team.name, role=Role.USER, content=p5_prompt)
        )
        artifacts["phase5_adversarial_red_team"] = resp5.content

        # ---------------------------------------------------------------------
        # Phase 6: Executive Synthesis & Deal Packager
        # ---------------------------------------------------------------------
        logger.info("[%s] Phase 6: Executive Synthesis & Enhancement Blueprint", self.pod_id)
        p6_prompt = (
            "Synthesize all agent findings into a polished, high-impact Executive Enhancement Blueprint:\n"
            "1. Executive Scorecard: Grade the current profile (A-F) across Market Appeal, IP Defensibility, Commercial Clarity, and Legal Protection.\n"
            "2. Top 5 Immediate Refinements: Concrete additions and revisions to integrate into COMPANY_PROFILE.md and JV_TERM_SHEET_TEMPLATE.md.\n"
            "3. Partner Pitch Narrative: A punchy, 3-minute executive elevator pitch for potential Joint Venture suitors.\n\n"
            f"Agent Findings Summary:\n"
            f"- Market Intel: {artifacts['phase1_market_intelligence'][:500]}...\n"
            f"- Product Strategy: {artifacts['phase2_product_strategy'][:500]}...\n"
            f"- Architecture: {artifacts['phase3_technical_architecture'][:500]}...\n"
            f"- Data Systems: {artifacts['phase4_data_engineering'][:500]}...\n"
            f"- Red Team Audit: {artifacts['phase5_adversarial_red_team'][:500]}...\n"
        )
        resp6 = await self.technical_writer.step(
            Message(sender="supervisor", recipient=self.technical_writer.name, role=Role.USER, content=p6_prompt)
        )
        artifacts["phase6_executive_synthesis"] = resp6.content

        elapsed = time.time() - start_time
        total_tokens = sum(getattr(a, "total_tokens_consumed", 0) for a in self.agents)
        merkle_hash = self._compute_merkle_provenance(artifacts)

        return ProfileEvaluationResult(
            pod_id=self.pod_id,
            success=True,
            market_intelligence=artifacts["phase1_market_intelligence"],
            product_strategy=artifacts["phase2_product_strategy"],
            technical_architecture_review=artifacts["phase3_technical_architecture"],
            data_engineering_review=artifacts["phase4_data_engineering"],
            adversarial_red_team_audit=artifacts["phase5_adversarial_red_team"],
            executive_synthesis=artifacts["phase6_executive_synthesis"],
            merkle_provenance_hash=merkle_hash,
            elapsed_seconds=elapsed,
            tokens_consumed=total_tokens,
            artifacts=artifacts,
        )
